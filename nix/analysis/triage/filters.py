"""Noise constants, path classifiers, filtering, and deduplication.

Adapted for BIRD. In scope are the daemon directories and client/ (kept in
sync with nix/analysis/roots.nix). The security-sensitive set is the code
that parses data from the network, the kernel or the control socket:
protocol packet parsers, BGP attributes and NLRI, flowspec, RPKI/RTR,
netlink, and the CLI socket.
"""

import fnmatch

from finding import Finding  # noqa: F401  (re-exported for callers)


# Trees whose findings are in scope for triage (roots.nix `dirs`).
ANALYSIS_ROOTS = tuple(d + '/' for d in (
    'client', 'conf', 'filter', 'lib', 'nest', 'proto', 'sysdep',
))

# Generated by bison / flex / m4. These live under obj/ (outside the roots)
# in an in-tree build; the names catch out-of-tree builds too.
GENERATED_FILE_PATTERNS = [
    'cf-parse.tab.c', 'cf-parse.tab.h', 'cf-parse.y', 'cf-lex.c',
    'keywords.h', 'commands.h', 'inst-gen.c', 'inst-gen.h',
    'inst-interpret.c', 'proto-build.c', 'paths.h',
]

EXCLUDED_CHECK_IDS = {
    # cppcheck tool limitations, not code bugs
    'missingIncludeSystem',
    'missingInclude',
    'unmatchedSuppression',
    'checkersReport',
    'syntaxError',                  # macro-heavy constructs (WALK_LIST, HASH_*)
    'preprocessorErrorDirective',
    'unknownMacro',
    'normalCheckLevelMaxBranches',
    'toomanyconfigs',
    # cppcheck false positives in idiomatic C
    'arithOperationsOnVoidPointer', # GNU C extension
    'subtractPointers',             # container_of
    # clang-tidy build errors (not findings)
    'clang-diagnostic-error',
    # _FORTIFY_SOURCE warnings (build config)
    '-W#warnings',
    '-Wcpp',
}

EXCLUDED_MESSAGE_PATTERNS = [
    '_FORTIFY_SOURCE',
]

TEST_PATH_PATTERNS = ['test/', '_test.c']

# Untrusted-input parsers: the prime fuzz targets.
SECURITY_PATHS = [
    'proto/bgp/packets.c', 'proto/bgp/attrs.c', 'proto/bgp/bgp.c',
    'proto/babel/packets.c', 'proto/bfd/packets.c', 'proto/rip/packets.c',
    'proto/radv/packets.c', 'proto/rpki/packets.c', 'proto/rpki/rpki.c',
    'proto/ospf/packet.c', 'proto/ospf/hello.c', 'proto/ospf/dbdes.c',
    'proto/ospf/lsreq.c', 'proto/ospf/lsupd.c', 'proto/ospf/lsack.c',
    'proto/ospf/lsalib.c', 'proto/ospf/topology.c',
    'proto/bmp/', 'proto/mrt/',
    'lib/flowspec.c', 'lib/net.c', 'lib/ip.c', 'lib/printf.c',
    'nest/a-path.c', 'nest/a-set.c', 'nest/rt-attr.c', 'nest/cli.c',
    'sysdep/linux/netlink.c', 'sysdep/bsd-netlink/', 'sysdep/bsd/krt-sock.c',
    'sysdep/unix/io.c',
]


def is_generated(path: str) -> bool:
    name = path.rsplit('/', 1)[-1]
    return any(fnmatch.fnmatch(name, pat) for pat in GENERATED_FILE_PATTERNS)


def is_third_party(path: str) -> bool:
    """Anything outside ANALYSIS_ROOTS (tests, tools, system headers)."""
    return not path.startswith(ANALYSIS_ROOTS)


def is_test_code(path: str) -> bool:
    return any(pat in path for pat in TEST_PATH_PATTERNS)


def is_security_sensitive(path: str) -> bool:
    return any(path.startswith(pat) for pat in SECURITY_PATHS)


def filter_findings(findings: list) -> list:
    """Remove out-of-scope code and known false positive categories."""
    return [
        f for f in findings
        if not is_third_party(f.file)
        and not is_generated(f.file)
        and f.check_id not in EXCLUDED_CHECK_IDS
        and f.line > 0
        and not any(pat in f.message for pat in EXCLUDED_MESSAGE_PATTERNS)
    ]


def deduplicate(findings: list) -> list:
    """Deduplicate by (file, line, check_id); headers repeat once per TU."""
    seen = set()
    result = []
    for f in findings:
        key = f.dedup_key()
        if key not in seen:
            seen.add(key)
            result.append(f)
    return result
